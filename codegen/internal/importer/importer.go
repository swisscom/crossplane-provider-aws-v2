// Package importer imports managed resource kinds from
// crossplane-contrib/provider-aws: their generator config, custom types and
// hand-written controller code. Code that cannot be ported mechanically is
// kept behind the importtodo build tag and listed in a report.
package importer

import (
	"context"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"golang.org/x/mod/modfile"

	"github.com/swisscom/crossplane-provider-aws-v2/codegen/internal/generator"
)

// SourceModule is the Go module of crossplane-contrib/provider-aws.
const SourceModule = "github.com/crossplane-contrib/provider-aws"

// Options of an import.
type Options struct {
	// Source is the root of a provider-aws checkout.
	Source string
	// Kinds to import, e.g. DBInstance.
	Kinds []string
	// Generator options; Service and OutputDir are required.
	generator.Options
}

var (
	serviceRe    = regexp.MustCompile(`^[a-z][a-z0-9]*$`)
	kindRe       = regexp.MustCompile(`^[A-Z][A-Za-z0-9]*$`)
	apiVersionRe = regexp.MustCompile(`^v[0-9]+((alpha|beta)[0-9]+)?$`)
)

// Validate checks Options before anything is written. The service and API
// version end up in paths, so they must not contain separators or dots.
func (o Options) Validate() error {
	if o.Source == "" || o.Service == "" || len(o.Kinds) == 0 {
		return errors.New("--source, --service and --kinds are required")
	}
	if !serviceRe.MatchString(strings.ToLower(o.Service)) {
		return fmt.Errorf("--service %q: must be an aws-sdk-go-v2 service package name (^[a-z][a-z0-9]*$)", o.Service)
	}
	for _, k := range o.Kinds {
		if !kindRe.MatchString(k) {
			return fmt.Errorf("--kinds: %q is not a kind name (^[A-Z][A-Za-z0-9]*$)", k)
		}
	}
	if !apiVersionRe.MatchString(o.APIVersion) {
		return fmt.Errorf("--api-version %q: must look like v1alpha1 (^v[0-9]+((alpha|beta)[0-9]+)?$)", o.APIVersion)
	}
	return nil
}

// Run imports o.Kinds of o.Service. It always returns a report, also
// together with an error, so callers can show what was done so far.
func Run(ctx context.Context, o Options) (*Report, error) {
	svc := strings.ToLower(o.Service)
	o.Service = svc
	r := &Report{Service: svc, Kinds: o.Kinds}
	if err := o.Validate(); err != nil {
		return r, err
	}
	return r, run(ctx, o, r)
}

func run(ctx context.Context, o Options, r *Report) error { //nolint:gocyclo // the import steps in order
	svc := o.Service

	srcCfg := filepath.Join(o.Source, "apis", svc, "generator-config.yaml")
	if _, err := os.Stat(srcCfg); err != nil {
		return fmt.Errorf("source has no generator config for %s: %w", svc, err)
	}
	if err := generator.ResolveServiceModule(&o.Options); err != nil {
		return err
	}

	lo := o.Options
	lo.GeneratorConfig = srcCfg
	all, err := generator.ListKinds(ctx, lo)
	if err != nil {
		return err
	}
	names := make([]string, 0, len(all))
	for _, k := range all {
		names = append(names, k.Name)
	}
	for _, k := range o.Kinds {
		if !slices.Contains(names, k) {
			return fmt.Errorf("kind %s is not generated by %s (kinds: %s)", k, srcCfg, strings.Join(names, ", "))
		}
	}

	m, err := readManifest(o.OutputDir, svc)
	if err != nil {
		return err
	}
	m.Source = SourceModule
	m.APIVersion = o.APIVersion
	for _, k := range o.Kinds {
		if !slices.Contains(m.Kinds, k) {
			m.Kinds = append(m.Kinds, k)
		}
	}
	// Controllers that exist are not overwritten, so they keep the
	// revision they were ported from.
	var fresh []string
	for _, k := range o.Kinds {
		if !controllerPorted(filepath.Join(o.OutputDir, "internal", "controller", svc, strings.ToLower(k))) {
			fresh = append(fresh, k)
		}
	}
	o.GeneratorConfig = filepath.Join(o.OutputDir, "apis", svc, "generator-config.yaml")
	if err := writeGeneratorConfig(srcCfg, o.GeneratorConfig, all, m, unresolvedIgnorePaths(ctx, o.Options), r); err != nil {
		return err
	}
	if err := writeManifest(o.OutputDir, svc, m); err != nil {
		return err
	}
	if err := generator.Run(ctx, o.Options); err != nil {
		return fmt.Errorf("cannot generate %s: %w", svc, err)
	}
	r.Kinds = m.Kinds

	tgt, err := loadTarget(o.OutputDir)
	if err != nil {
		return err
	}
	rw := newRewriter(tgt.module, tgt.apiAvailable)
	svcVer := svc + "/" + o.APIVersion
	src, err := parseAPIPackage(filepath.Join(o.Source, "apis", svc, o.APIVersion), SourceModule+"/apis/"+svcVer)
	if err != nil {
		return fmt.Errorf("cannot parse source API package: %w", err)
	}
	var ctrlDirs []string
	for _, k := range o.Kinds {
		ctrlDirs = append(ctrlDirs, filepath.Join(o.Source, "pkg", "controller", svc, strings.ToLower(k)))
	}
	uses, err := apiUses(ctrlDirs, src.path)
	if err != nil {
		return fmt.Errorf("cannot parse source controllers: %w", err)
	}
	ct := &customTypes{src: src, svcVer: svcVer, kinds: o.Kinds, srcKinds: names, tgt: tgt, rw: rw, report: r, ctrlUses: uses}
	if err := ct.run(); err != nil {
		return fmt.Errorf("cannot import custom types: %w", err)
	}

	// deepcopy and managed resource methods of the new types
	if err := goGenerate(ctx, filepath.Join(tgt.root, "apis")); err != nil {
		return err
	}
	if err := ct.writeOther(); err != nil {
		return err
	}
	if err := reportResolverGaps(filepath.Join(tgt.root, "apis", svcVer), ct.written, r); err != nil {
		return fmt.Errorf("cannot check references: %w", err)
	}
	if rw.sdk[svc], err = loadSDKNames(o.OutputDir, svc); err != nil {
		return err
	}
	im := &importer{ctx: ctx, o: o, src: o.Source, tgt: tgt, rw: rw, report: r, newDirs: map[string]bool{}, todo: map[string]int{}}
	for _, k := range o.Kinds {
		lower := strings.ToLower(k)
		srcDir := filepath.Join(o.Source, "pkg", "controller", svc, lower)
		if _, err := os.Stat(srcDir); err != nil {
			r.Add(topicController, "%s: no controller in the source (%s)", k, srcDir)
			continue
		}
		rel := filepath.Join("internal", "controller", svc, lower)
		if err := im.portPackage(srcDir, filepath.Join(tgt.root, rel), tgt.module+"/"+filepath.ToSlash(rel), k); err != nil {
			return fmt.Errorf("cannot port controller of %s: %w", k, err)
		}
	}
	if err := im.portHelpers(); err != nil {
		return fmt.Errorf("cannot port helper packages: %w", err)
	}
	if err := im.typecheck(); err != nil {
		return fmt.Errorf("cannot type check ported code: %w", err)
	}
	recordRevisions(o, m, fresh, im.helpers, r)
	return writeManifest(o.OutputDir, svc, m)
}

// recordRevisions records the source revision of what this run read: per
// freshly ported kind, and for the whole run in lastImport.
func recordRevisions(o Options, m *Manifest, fresh, helpers []string, r *Report) {
	svc := o.Service
	controller := func(k string) string { return "pkg/controller/" + svc + "/" + strings.ToLower(k) }
	for _, k := range fresh {
		rev, err := sourceRevision(o.Source, append([]string{"apis/" + svc, controller(k)}, helpers...))
		if err != nil {
			r.Block(topicController, "%s: source revision not recorded: %v", k, err)
			continue
		}
		if m.Revisions == nil {
			m.Revisions = map[string]Revision{}
		}
		m.Revisions[k] = rev
	}
	paths := append([]string{"apis/" + svc}, helpers...)
	for _, k := range o.Kinds {
		paths = append(paths, controller(k))
	}
	rev, err := sourceRevision(o.Source, paths)
	if err != nil {
		r.Block(topicController, "lastImport: source revision not recorded: %v", err)
		return
	}
	m.LastImport = &rev
}

// unresolvedIgnorePaths asks the generator which ignore paths of a
// candidate config match nothing in the API model.
func unresolvedIgnorePaths(ctx context.Context, o generator.Options) unresolvedFunc {
	return func(cfg []byte) ([]string, error) {
		if err := os.MkdirAll(filepath.Dir(o.GeneratorConfig), 0o750); err != nil {
			return nil, err
		}
		f, err := os.CreateTemp(filepath.Dir(o.GeneratorConfig), ".generator-config-*.yaml")
		if err != nil {
			return nil, err
		}
		defer os.Remove(f.Name()) //nolint:errcheck // best effort
		if _, err := f.Write(cfg); err != nil {
			f.Close() //nolint:errcheck,gosec // the write error wins
			return nil, err
		}
		if err := f.Close(); err != nil {
			return nil, err
		}
		o.GeneratorConfig = f.Name()
		return generator.UnresolvedIgnoreFieldPaths(ctx, o)
	}
}

func goGenerate(ctx context.Context, dir string) error {
	cmd := exec.CommandContext(ctx, "go", "generate", "-tags", "generate", "./...")
	cmd.Dir = dir
	if out, err := cmd.CombinedOutput(); err != nil {
		return fmt.Errorf("go generate in %s failed: %w\n%s", dir, err, out)
	}
	return nil
}

// loadTarget reads the module path and the import manifests of the target.
func loadTarget(root string) (*target, error) {
	root, err := filepath.Abs(root)
	if err != nil {
		return nil, err
	}
	gm, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return nil, err
	}
	t := &target{root: root, module: modfile.ModulePath(gm), kinds: map[string]map[string]bool{}}
	dirs, err := filepath.Glob(filepath.Join(root, "apis", "*", "import.yaml"))
	if err != nil {
		return nil, err
	}
	for _, d := range dirs {
		svc := filepath.Base(filepath.Dir(d))
		m, err := readManifest(root, svc)
		if err != nil {
			return nil, err
		}
		v := m.APIVersion
		if v == "" {
			v = "v1alpha1"
		}
		ks := map[string]bool{}
		for _, k := range m.Kinds {
			ks[k] = true
		}
		t.kinds[svc+"/"+v] = ks
	}
	return t, nil
}
