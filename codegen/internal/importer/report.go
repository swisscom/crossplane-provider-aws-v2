package importer

import (
	"fmt"
	"slices"
	"sort"
	"strings"
)

// Finding is one line of an import report.
type Finding struct {
	Text string
	// Blocking findings need a human before the import is done.
	Blocking bool
}

// Report lists what an import did and what is left to port by hand.
type Report struct {
	Service string
	Kinds   []string
	// Items are findings, grouped by file or topic.
	Items map[string][]Finding
}

// Add records a notice about a file or topic.
func (r *Report) Add(topic, format string, args ...any) {
	r.add(topic, false, format, args...)
}

// Block records a blocking finding: something the import could not port
// and a human has to.
func (r *Report) Block(topic, format string, args ...any) {
	r.add(topic, true, format, args...)
}

func (r *Report) add(topic string, blocking bool, format string, args ...any) {
	if r.Items == nil {
		r.Items = map[string][]Finding{}
	}
	r.Items[topic] = append(r.Items[topic], Finding{Text: fmt.Sprintf(format, args...), Blocking: blocking})
}

// Blocking returns the number of blocking findings.
func (r *Report) Blocking() int {
	n := 0
	for _, fs := range r.Items {
		for _, f := range fs {
			if f.Blocking {
				n++
			}
		}
	}
	return n
}

// Markdown renders the report. Findings are sorted, so the output does not
// depend on the order in which they were added.
func (r *Report) Markdown() string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Import report: %s (%s)\n\n", r.Service, strings.Join(r.Kinds, ", "))
	b.WriteString("Generated by codegen/cmd/import. Files tagged `//go:build importtodo` are excluded from the build until ported.\n\n")
	if n := r.Blocking(); n > 0 {
		fmt.Fprintf(&b, "**%d blocking finding(s).** The import is not done: fix each one and remove its `TODO(import)` marker. `make check-import-todo` fails until then.\n", n)
	} else {
		b.WriteString("No blocking findings.\n")
	}
	topics := make([]string, 0, len(r.Items))
	for t := range r.Items {
		topics = append(topics, t)
	}
	sort.Strings(topics)
	for _, t := range topics {
		fs := slices.Clone(r.Items[t])
		slices.SortFunc(fs, func(a, b Finding) int {
			if a.Blocking != b.Blocking {
				if a.Blocking {
					return -1
				}
				return 1
			}
			return strings.Compare(a.Text, b.Text)
		})
		fmt.Fprintf(&b, "\n## %s\n\n", t)
		for _, f := range fs {
			if f.Blocking {
				b.WriteString("- **blocking:** ")
			} else {
				b.WriteString("- ")
			}
			b.WriteString(f.Text + "\n")
		}
	}
	return b.String()
}
