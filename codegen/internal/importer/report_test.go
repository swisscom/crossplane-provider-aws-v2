package importer

import (
	"strings"
	"testing"
)

func TestReportMarkdown(t *testing.T) {
	type finding struct {
		topic, text string
		blocking    bool
	}
	findings := []finding{
		{"Controller", "b notice", false},
		{"Controller", "z blocker", true},
		{"API types", "a notice", false},
		{"Controller", "a notice", false},
		{"Controller", "y blocker", true},
	}
	build := func(order []int) *Report {
		r := &Report{Service: "svc", Kinds: []string{fooKind, "Bar"}}
		for _, i := range order {
			f := findings[i]
			if f.blocking {
				r.Block(f.topic, "%s", f.text)
			} else {
				r.Add(f.topic, "%s", f.text)
			}
		}
		return r
	}
	a := build([]int{0, 1, 2, 3, 4})
	b := build([]int{4, 3, 2, 1, 0})
	if a.Markdown() != b.Markdown() {
		t.Errorf("Markdown() depends on the order of findings:\n%s\n---\n%s", a.Markdown(), b.Markdown())
	}
	if got := a.Blocking(); got != 2 {
		t.Errorf("Blocking() = %d, want 2", got)
	}
	want := "# Import report: svc (Foo, Bar)\n\n" +
		"Generated by codegen/cmd/import. Files tagged `//go:build importtodo` are excluded from the build until ported.\n\n" +
		"**2 blocking finding(s).** The import is not done: fix each one and remove its `TODO(import)` marker. `make check-import-todo` fails until then.\n" +
		"\n## API types\n\n- a notice\n" +
		"\n## Controller\n\n- **blocking:** y blocker\n- **blocking:** z blocker\n- a notice\n- b notice\n"
	if got := a.Markdown(); got != want {
		t.Errorf("Markdown() =\n%s\nwant\n%s", got, want)
	}

	clean := &Report{Service: "svc"}
	clean.Add("Controller", "fine")
	if clean.Blocking() != 0 || !strings.Contains(clean.Markdown(), "\nNo blocking findings.\n") {
		t.Errorf("clean report: Blocking() = %d, Markdown() =\n%s", clean.Blocking(), clean.Markdown())
	}
}
